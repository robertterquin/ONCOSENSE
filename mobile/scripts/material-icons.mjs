// Icons that also ship at a heavier weight (small ticks and pluses that need to read).
const BOLD = ['check', 'plus'];

const [regularDir, boldDir] = process.argv.slice(2);
if (!regularDir || !boldDir)
  throw new Error('Usage: node scripts/material-icons.mjs <svg-300> <svg-600>');

const path = (dir, symbol) => {
  const svg = readFileSync(join(dir, 'rounded', `${symbol}.svg`), 'utf8');
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  if (!d.length) throw new Error(`No path in ${symbol}`);
  return d.join('');
};

const lines = Object.entries(ICONS).map(
  ([name, symbol]) => `  '${name}': '${path(regularDir, symbol)}',`,
);
const bold = BOLD.map((name) => `  '${name}': '${path(boldDir, ICONS[name])}',`);

writeFileSync(
  new URL('../src/components/ui/materialIcons.ts', import.meta.url),
  `// Generated by scripts/material-icons.mjs from Material Symbols Rounded (Apache 2.0).
// Don't edit by hand. Paths are in a 960 x 960 box (viewBox "0 -960 960 960").

/** Weight 300, to sit with Atkinson Hyperlegible Next. */
export const MATERIAL_ICONS = {
${lines.join('\n')}
} as const;

/** Weight 600, for small marks that must stand out. */
export const MATERIAL_ICONS_BOLD: Partial<Record<keyof typeof MATERIAL_ICONS, string>> = {
${bold.join('\n')}
};
`,
);
console.log(`Wrote ${lines.length} icons (${bold.length} bold).`);
